import statistics
salaries =[10000,20000,40000,50000,35000,200000]

# 2. Calculate Central Tendency
mean_val = statistics.mean(salaries)
mode_val = statistics.mode(salaries)
median_val = statistics.median(salaries)
print(mean_val)
print(mode_val)
print(median_val)

std_dev = statistics.stdev(salaries)
print(std_dev)

variance_val = statistics.variance(salaries)
print(variance_val)

import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np

# Set style
sns.set_theme(style="whitegrid")

# Create subplots
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# Histogram with KDE
sns.histplot(salaries, kde=True, ax=axes[0], color='skyblue')
axes[0].set_title('Salary Distribution Histogram')
axes[0].set_xlabel('Salary')
axes[0].set_ylabel('Frequency')

# Boxplot to highlight outliers
sns.boxplot(x=salaries, ax=axes[1], color='lightgreen')
axes[1].set_title('Salary Distribution Boxplot')
axes[1].set_xlabel('Salary')

plt.tight_layout()
plt.show()

# Calculate Interquartile Range (IQR) to mathematically identify outliers
q1 = np.percentile(salaries, 25)
q3 = np.percentile(salaries, 75)
iqr = q3 - q1

lower_bound = q1 - 1.5 * iqr
upper_bound = q3 + 1.5 * iqr

outliers = [x for x in salaries if x < lower_bound or x > upper_bound]

print(f"Q1 (25th percentile): {q1}")
print(f"Q3 (75th percentile): {q3}")
print(f"IQR: {iqr}")
print(f"Lower Bound for Outliers: {lower_bound}")
print(f"Upper Bound for Outliers: {upper_bound}")
print(f"Identified Outliers: {outliers}")

