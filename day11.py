data = {
     'Month': ['Jan', 'Feb', 'Mar', 'Apr', 'May'],
    'Profit': [10000, 13000, 12000, 18000, 25000]
}
df = pd.DataFrame(data)

import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd
# Create the Line Chart
plt.figure(figsize=(7, 4)) # Sets the window width and height
sns.lineplot(x='Month', y='Profit', data=df, marker='o', color='blue', linewidth=2.5)

# Create the Bar Chart
plt.figure(figsize=(7, 4))
sns.barplot(x='Month', y='Profit', data=df, hue='Month', palette='Blues_d', legend=False)
plt.title('Monthly Profit')
plt.xlabel('Month')
plt.ylabel('Profit ($)')
plt.show()

# Create the Histogram
plt.figure(figsize=(7, 4))
sns.histplot(data=df, x='Profit', bins=5, kde=True, color='teal')
plt.title('Distribution of Monthly Profits')
plt.xlabel('Profit ($)')
plt.ylabel('Count')
plt.show()

# Create the Box Plot
plt.figure(figsize=(6, 4))
sns.boxplot(y='Profit', data=df, color='lightblue', width=0.4)
plt.title('Box Plot of Monthly Profits')
plt.ylabel('Profit ($)')
plt.show()

# Create the Scatter Plot
plt.figure(figsize=(7, 4))
sns.scatterplot(x='Month', y='Profit', data=df, s=100, color='red', marker='o')
plt.title('Scatter Plot of Monthly Profits')
plt.xlabel('Month')
plt.ylabel('Profit ($)')
plt.grid(True, linestyle='--', alpha=0.5)
plt.show()

# Calculate correlation after converting Month to a numeric index
df_numeric = df.copy()
df_numeric['Month_Index'] = range(1, len(df) + 1)
corr_matrix = df_numeric[['Month_Index', 'Profit']].corr()

# Create the Heatmap
plt.figure(figsize=(6, 4))
sns.heatmap(corr_matrix, annot=True, cmap='coolwarm', vmin=-1, vmax=1, square=True)
plt.title('Correlation Heatmap')
plt.show()